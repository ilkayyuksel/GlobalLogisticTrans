/**
 * Every visible string in the application shell, in both languages.
 *
 * A plain object rather than an i18n framework. This application has two
 * languages, no pluralisation rules, no date-format negotiation and no
 * translator workflow — a library would add a build step, a loader and a
 * runtime for something a typed record already does correctly.
 *
 * The Dutch wording is the product's own vocabulary and is authoritative:
 * "Ritten" for transport orders, "Agenda" for general appointments. Turkish is
 * a natural translation of the same intent, not a word-for-word mapping.
 *
 * `Translations` is derived from the Dutch dictionary, so every language must
 * define exactly the same keys — a missing or misspelled key is a compile
 * error, not a blank label discovered in production.
 */

